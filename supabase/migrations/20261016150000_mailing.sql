-- Mailing (Settings > Mailing; src/lib/mailing/): mailing lists, the people on them (contacts, with how and
-- when they agreed), campaigns and weekly digests sent through Mailgun, and what happened to each email
-- (sends, links and clicks, Mailgun's events). None of it is synced or backed up: it stays on the copy
-- where it was made, so a restore can never subscribe anyone again. The site writes from public routes
-- with the service key; editors read through their session, admins change contacts and lists.

create table public.mail_lists (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  -- Offered by Subscribe blocks and on the preferences page.
  public boolean not null default true,
  sort integer not null default 0,
  created_at timestamptz not null default now()
);

create table public.contacts (
  id bigint generated by default as identity primary key,
  email text not null unique check (email = lower(email)),
  name text not null default '',
  attributes jsonb not null default '{}'::jsonb,
  -- Anything but subscribed means no marketing mail at all.
  status text not null default 'pending' check (status in ('pending', 'subscribed', 'unsubscribed', 'bounced', 'complained')),
  -- How they agreed: form:<id>, subscribe:<path>, members, import:<name>, admin, preferences.
  consent_source text not null default '',
  consent_text text not null default '',
  consent_at timestamptz,
  consent_ip text not null default '',
  confirmed_at timestamptz,
  unsubscribed_at timestamptz,
  -- Confirmation emails sent today (at most 3 a day to one address).
  confirm_day date,
  confirm_count integer not null default 0,
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index contacts_status on public.contacts (status);
create trigger contacts_touch before update on public.contacts for each row execute function public.touch_updated_at();

create table public.contact_lists (
  contact_id bigint not null references public.contacts on delete cascade,
  list_id bigint not null references public.mail_lists on delete cascade,
  -- pending: asked for, waiting for the address to be confirmed.
  status text not null default 'pending' check (status in ('pending', 'subscribed', 'unsubscribed')),
  subscribed_at timestamptz,
  unsubscribed_at timestamptz,
  primary key (contact_id, list_id)
);
create index contact_lists_list on public.contact_lists (list_id, status);

-- Addresses that must never be mailed again without a fresh confirmed sign-up: erased contacts, bounces
-- and complaints. SHA-256 of the lowercased address.
create table public.mail_suppressions (
  email_hash text primary key,
  reason text not null default '',
  created_at timestamptz not null default now()
);

create table public.digests (
  id bigint generated by default as identity primary key,
  name text not null default 'Weekly digest',
  list_ids bigint[] not null default '{}',
  -- { members: any | members | non-members, levels: [] }
  audience jsonb not null default '{}'::jsonb,
  -- 0 Sunday .. 6 Saturday, and HH:MM, in the site's time zone.
  weekday integer not null default 4 check (weekday between 0 and 6),
  send_time text not null default '09:00' check (send_time ~ '^\d{2}:\d{2}$'),
  subject text not null default '',
  from_name text not null default '',
  reply_to text not null default '',
  design jsonb,
  text text not null default '',
  -- auto: sent at its time; review: a draft at its time, sent review_hours later once an admin approves it.
  mode text not null default 'review' check (mode in ('auto', 'review')),
  review_hours integer not null default 24 check (review_hours between 1 and 168),
  skip_when_empty boolean not null default true,
  min_items integer not null default 1 check (min_items >= 0),
  track_links boolean not null default true,
  utm boolean not null default true,
  enabled boolean not null default false,
  -- The ISO week of the last issue made (2026-W42), so an issue is made once a week.
  last_run_key text,
  last_run_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create trigger digests_touch before update on public.digests for each row execute function public.touch_updated_at();

create table public.campaigns (
  id bigint generated by default as identity primary key,
  name text not null default '',
  subject text not null default '',
  from_name text not null default '',
  reply_to text not null default '',
  design jsonb,
  text text not null default '',
  list_ids bigint[] not null default '{}',
  audience jsonb not null default '{}'::jsonb,
  -- review: a digest's issue waiting for an admin; skipped: a digest issue with too little in it.
  status text not null default 'draft' check (status in ('draft', 'review', 'scheduled', 'sending', 'sent', 'paused', 'cancelled', 'failed', 'skipped')),
  scheduled_at timestamptz,
  started_at timestamptz,
  sent_at timestamptz,
  digest_id bigint references public.digests on delete set null,
  issue_key text,
  -- New since this time (a digest's Entries blocks).
  since timestamptz,
  track_links boolean not null default true,
  utm boolean not null default false,
  -- Frozen when sending starts: what went out.
  html text,
  text_rendered text,
  vars jsonb,
  recipients integer not null default 0,
  claim_token text,
  claimed_at timestamptz,
  error text not null default '',
  created_by uuid references auth.users on delete set null,
  sent_by uuid references auth.users on delete set null,
  approved_by uuid references auth.users on delete set null,
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index campaigns_issue on public.campaigns (digest_id, issue_key) where digest_id is not null;
create index campaigns_due on public.campaigns (status, scheduled_at);
create trigger campaigns_touch before update on public.campaigns for each row execute function public.touch_updated_at();

create table public.campaign_batches (
  id bigint generated by default as identity primary key,
  campaign_id bigint not null references public.campaigns on delete cascade,
  n integer not null,
  -- unknown: the request's outcome wasn't seen (a timeout); checked with Mailgun before any resend.
  status text not null default 'pending' check (status in ('pending', 'attempting', 'accepted', 'failed', 'unknown', 'skipped')),
  mailgun_id text,
  attempts integer not null default 0,
  error text not null default '',
  attempted_at timestamptz,
  updated_at timestamptz not null default now(),
  unique (campaign_id, n)
);

create table public.campaign_sends (
  campaign_id bigint not null references public.campaigns on delete cascade,
  contact_id bigint not null references public.contacts on delete cascade,
  batch_id bigint references public.campaign_batches on delete set null,
  email text not null,
  -- dropped: no longer subscribed when its batch went.
  status text not null default 'queued' check (status in ('queued', 'dropped', 'sent', 'delivered', 'failed', 'bounced', 'complained')),
  delivered_at timestamptz,
  opened_at timestamptz,
  clicked_at timestamptz,
  machine_clicked_at timestamptz,
  human_confirmed_at timestamptz,
  bounced_at timestamptz,
  complained_at timestamptz,
  unsubscribed_at timestamptz,
  primary key (campaign_id, contact_id)
);
create index campaign_sends_batch on public.campaign_sends (batch_id);
create index campaign_sends_contact on public.campaign_sends (contact_id);

create table public.campaign_links (
  id bigint generated by default as identity primary key,
  campaign_id bigint not null references public.campaigns on delete cascade,
  url text not null,
  label text not null default '',
  position integer not null default 0,
  kind text not null default 'content' check (kind in ('content', 'honeypot'))
);
create index campaign_links_campaign on public.campaign_links (campaign_id);

create table public.link_clicks (
  id bigint generated by default as identity primary key,
  link_id bigint not null references public.campaign_links on delete cascade,
  campaign_id bigint not null,
  contact_id bigint,
  at timestamptz not null default now(),
  method text not null default 'GET',
  user_agent text not null default '',
  -- /24 of IPv4, /48 of IPv6: never the whole address.
  ip_prefix text not null default '',
  country text not null default '',
  -- The address was in a mail scanner's range (src/lib/mailing/clicks.ts) when it came in.
  scanner_ip boolean not null default false,
  verdict text not null default 'likely_human' check (verdict in ('machine', 'likely_human', 'human')),
  reasons text[] not null default '{}',
  confirmed_at timestamptz
);
create index link_clicks_send on public.link_clicks (campaign_id, contact_id, at);
create index link_clicks_at on public.link_clicks (at);

create table public.mail_events (
  id bigint generated by default as identity primary key,
  event_id text not null unique,
  event text not null,
  severity text not null default '',
  recipient text not null default '',
  campaign_id bigint,
  -- opens: machine, privacy (a proxy such as Apple's) or likely_human.
  verdict text not null default '',
  payload jsonb not null default '{}'::jsonb,
  received_at timestamptz not null default now()
);
create index mail_events_campaign on public.mail_events (campaign_id, event);
create index mail_events_received on public.mail_events (received_at);

-- Webhook tokens seen (a token used twice is refused); pruned after a day.
create table public.mailgun_tokens (
  token text primary key,
  at timestamptz not null default now()
);

