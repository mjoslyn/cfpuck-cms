-- A campaign's audience: subscribed contacts on any of its lists, not suppressed, and (optionally) only
-- members, of some levels, or only people who aren't members.
create or replace function public.mail_audience(p_lists bigint[], p_members text default 'any', p_levels text[] default '{}')
returns table (id bigint, email text, name text, attributes jsonb)
language sql
stable
set search_path = ''
as $$
  select c.id, c.email, c.name, c.attributes
  from public.contacts c
  where c.status = 'subscribed'
    and exists (select 1 from public.contact_lists cl where cl.contact_id = c.id and cl.status = 'subscribed' and cl.list_id = any (p_lists))
    and not exists (select 1 from public.mail_suppressions s where s.email_hash = encode(extensions.digest(c.email, 'sha256'), 'hex'))
    and (
      coalesce(p_members, 'any') = 'any'
      or (p_members = 'members') = exists (
        select 1 from public.members m
        where lower(m.email) = c.email and m.status = 'active' and (m.expires_on is null or m.expires_on >= current_date)
          and (coalesce(cardinality(p_levels), 0) = 0 or m.level = any (p_levels))
      )
    )
  order by c.id
$$;

-- Of some contacts, those still subscribed to any of the lists (checked again just before each batch).
create or replace function public.mail_still_subscribed(p_ids bigint[], p_lists bigint[])
returns setof bigint
language sql
stable
set search_path = ''
as $$
  select c.id from public.contacts c
  where c.id = any (p_ids) and c.status = 'subscribed'
    and exists (select 1 from public.contact_lists cl where cl.contact_id = c.id and cl.status = 'subscribed' and cl.list_id = any (p_lists))
    and not exists (select 1 from public.mail_suppressions s where s.email_hash = encode(extensions.digest(c.email, 'sha256'), 'hex'))
$$;

-- Claim a campaign for one sending run: free, or its last run silent for 16 minutes (a killed worker).
create or replace function public.mail_claim(p_id bigint, p_token text)
returns boolean
language plpgsql
set search_path = ''
as $$
begin
  update public.campaigns
    set claim_token = p_token, claimed_at = now(), status = 'sending', started_at = coalesce(started_at, now())
    where id = p_id and status in ('scheduled', 'sending')
      and (claim_token is null or claimed_at < now() - interval '16 minutes');
  return found;
end;
$$;

-- Take a digest's issue for a week: true for the one run that sets the week's key.
create or replace function public.mail_digest_claim(p_id bigint, p_key text)
returns boolean
language plpgsql
set search_path = ''
as $$
begin
  update public.digests set last_run_key = p_key, last_run_at = now()
    where id = p_id and last_run_key is distinct from p_key;
  return found;
end;
$$;

-- A campaign's numbers, from its sends and clicks.
create or replace function public.campaign_stats(p_id bigint)
returns jsonb
language sql
stable
set search_path = ''
as $$
  select jsonb_build_object(
    'recipients', count(*) filter (where s.status <> 'dropped'),
    'queued', count(*) filter (where s.status = 'queued'),
    'dropped', count(*) filter (where s.status = 'dropped'),
    'sent', count(*) filter (where s.status not in ('queued', 'dropped')),
    'delivered', count(*) filter (where s.delivered_at is not null),
    'bounced', count(*) filter (where s.bounced_at is not null),
    'complained', count(*) filter (where s.complained_at is not null),
    'unsubscribed', count(*) filter (where s.unsubscribed_at is not null),
    'opened', count(*) filter (where s.opened_at is not null),
    'clicked', count(*) filter (where s.clicked_at is not null),
    'confirmed', count(*) filter (where s.human_confirmed_at is not null),
    'machine', count(*) filter (where s.machine_clicked_at is not null)
  )
  from public.campaign_sends s where s.campaign_id = p_id
$$;

