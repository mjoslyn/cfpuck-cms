-- Saved email designs, offered in the email builder to start an email from (src/lib/email-templates.ts).
-- `kit` is the builder that made it (mailing: campaigns and digests; form: form notifications; ticket:
-- ticket emails), whose blocks it holds. `default_for` names what new emails of a kind start from
-- (campaign, digest, form, ticket:<kind>); at most one template each.
create table public.email_templates (
  id bigint generated by default as identity primary key,
  kit text not null check (kit in ('mailing', 'form', 'ticket')),
  name text not null,
  design jsonb not null,
  text text not null default '',
  default_for text unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create trigger email_templates_touch before update on public.email_templates for each row execute function public.touch_updated_at();

alter table public.email_templates enable row level security;
create policy "email templates editor all" on public.email_templates for all to authenticated
  using ((select public.is_editor())) with check ((select public.is_editor()));
grant select, insert, update, delete on public.email_templates to authenticated, service_role;
