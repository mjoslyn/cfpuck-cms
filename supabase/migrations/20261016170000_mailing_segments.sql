-- Mailing segments (src/lib/mailing/segments.ts): saved rules that pick some of the people on a campaign's
-- lists, members or not: on another list, tagged, a field's value, a member or not, how recently they
-- signed up, opened or clicked, where they signed up. Contacts get tags (lowercased) to segment by, beside
-- their fields (attributes). A campaign or digest can name a segment; its audience is then the people on
-- its lists who match it. A segment in use can't be deleted, so an audience never widens on its own.

alter table public.contacts add column tags text[] not null default '{}';
create index contacts_tags on public.contacts using gin (tags);

create table public.mail_segments (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  -- { match: all | any, rules: [{ type, not?, ... }] }
  rules jsonb not null default '{"match": "all", "rules": []}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create trigger mail_segments_touch before update on public.mail_segments for each row execute function public.touch_updated_at();

alter table public.mail_segments enable row level security;
create policy "mail segments editor all" on public.mail_segments for all to authenticated
  using ((select public.is_editor())) with check ((select public.is_editor()));
grant select, insert, update, delete on public.mail_segments to authenticated, service_role;

alter table public.campaigns add column segment_id bigint references public.mail_segments on delete restrict;
alter table public.digests add column segment_id bigint references public.mail_segments on delete restrict;

-- Whether a contact matches one rule (r.not turns it round). Types: list (subscribed to any of r.lists),
-- tag (any of r.tags), field (r.key: r.op set, equals or contains r.value, ignoring case), member (an
-- active member, of any of r.levels or any level), joined (signed up in the last r.days days), opened and
-- clicked (an email in the last r.days days; clicks by people, not machines), source (where they signed
-- up contains r.value).
create or replace function public.mail_rule(c public.contacts, r jsonb)
returns boolean
language sql
stable
set search_path = ''
as $$
  select coalesce((r->>'not')::boolean, false) <> coalesce(
    case r->>'type'
      when 'list' then exists (
        select 1 from public.contact_lists cl
        where cl.contact_id = c.id and cl.status = 'subscribed'
          and cl.list_id in (select x::bigint from jsonb_array_elements_text(coalesce(r->'lists', '[]'::jsonb)) x))
      when 'tag' then c.tags && array(select lower(x) from jsonb_array_elements_text(coalesce(r->'tags', '[]'::jsonb)) x)
      when 'field' then case r->>'op'
        when 'set' then coalesce(c.attributes->>(r->>'key'), '') <> ''
        when 'equals' then lower(coalesce(c.attributes->>(r->>'key'), '')) = lower(coalesce(r->>'value', ''))
        when 'contains' then position(lower(coalesce(r->>'value', '')) in lower(coalesce(c.attributes->>(r->>'key'), ''))) > 0
        else false
      end
      when 'member' then exists (
        select 1 from public.members m
        where lower(m.email) = c.email and m.status = 'active' and (m.expires_on is null or m.expires_on >= current_date)
          and (coalesce(jsonb_array_length(r->'levels'), 0) = 0 or m.level in (select jsonb_array_elements_text(r->'levels'))))
      when 'joined' then coalesce(c.confirmed_at, c.consent_at, c.created_at) >= now() - make_interval(days => greatest(coalesce((r->>'days')::int, 0), 0))
      when 'opened' then exists (
        select 1 from public.campaign_sends s
        where s.contact_id = c.id and s.opened_at >= now() - make_interval(days => greatest(coalesce((r->>'days')::int, 0), 0)))
      when 'clicked' then exists (
        select 1 from public.campaign_sends s
        where s.contact_id = c.id and s.clicked_at >= now() - make_interval(days => greatest(coalesce((r->>'days')::int, 0), 0)))
      when 'source' then position(lower(coalesce(r->>'value', '')) in lower(c.consent_source)) > 0
      else false
    end, false)
$$;

-- Whether a contact matches a segment ({ match, rules }; no rules: everyone).
create or replace function public.mail_segment_match(c public.contacts, s jsonb)
returns boolean
language sql
stable
set search_path = ''
as $$
  select s is null or coalesce(jsonb_array_length(s->'rules'), 0) = 0 or (
    case when s->>'match' = 'any'
      then exists (select 1 from jsonb_array_elements(s->'rules') r where public.mail_rule(c, r))
      else not exists (select 1 from jsonb_array_elements(s->'rules') r where not public.mail_rule(c, r))
    end)
$$;

-- A campaign's audience, now with a segment: subscribed contacts on any of its lists (no lists given: on
-- any list), not suppressed, members or non-members as before, and matching the segment.
drop function public.mail_audience(bigint[], text, text[]);
create or replace function public.mail_audience(p_lists bigint[], p_members text default 'any', p_levels text[] default '{}', p_segment jsonb default null)
returns table (id bigint, email text, name text, attributes jsonb)
language sql
stable
set search_path = ''
as $$
  select c.id, c.email, c.name, c.attributes
  from public.contacts c
  where c.status = 'subscribed'
    and exists (select 1 from public.contact_lists cl where cl.contact_id = c.id and cl.status = 'subscribed' and (p_lists is null or cl.list_id = any (p_lists)))
    and not exists (select 1 from public.mail_suppressions s where s.email_hash = encode(extensions.digest(c.email, 'sha256'), 'hex'))
    and (
      coalesce(p_members, 'any') = 'any'
      or (p_members = 'members') = exists (
        select 1 from public.members m
        where lower(m.email) = c.email and m.status = 'active' and (m.expires_on is null or m.expires_on >= current_date)
          and (coalesce(cardinality(p_levels), 0) = 0 or m.level = any (p_levels))
      )
    )
    and public.mail_segment_match(c, p_segment)
  order by c.id
$$;

revoke execute on function public.mail_rule(public.contacts, jsonb) from public, anon, authenticated;
revoke execute on function public.mail_segment_match(public.contacts, jsonb) from public, anon, authenticated;
revoke execute on function public.mail_audience(bigint[], text, text[], jsonb) from public, anon, authenticated;
grant execute on function public.mail_rule(public.contacts, jsonb) to service_role;
grant execute on function public.mail_segment_match(public.contacts, jsonb) to service_role;
grant execute on function public.mail_audience(bigint[], text, text[], jsonb) to service_role;
