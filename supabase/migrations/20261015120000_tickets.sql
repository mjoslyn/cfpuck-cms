-- Event tickets (src/lib/tickets/). An event's ticket types live in its fields (fields.tickets); each
-- purchase or free registration is an order here. Orders hold buyers' names and email addresses, so
-- only editors read them; the site writes them with the service key. Visitors see two things through
-- functions: how many of each ticket type are taken, and one order's status by its secret token.

create table public.ticket_orders (
  id bigint generated by default as identity primary key,
  -- The buyer's link to their order (/<event>/?order=<token>); never shown to anyone else.
  token text not null unique,
  -- Shown on the confirmation and at the door.
  code text not null unique,
  entry_id bigint references public.entries (id) on delete set null,
  -- A recurring event's date (Y-m-d); '' for a single event.
  occurrence text not null default '',
  event_title text not null default '',
  status text not null default 'pending' check (status in ('pending', 'paid', 'cancelled', 'expired', 'refunded')),
  provider text not null check (provider in ('free', 'stripe', 'square')),
  -- Stripe Checkout Session id, or Square payment link id.
  provider_ref text,
  -- Square's order id.
  provider_order text,
  -- Stripe payment intent, or Square payment id.
  provider_payment text,
  name text not null,
  email text not null,
  phone text not null default '',
  -- { line1, line2, city, state, zip, country } when the event asks for it.
  address jsonb,
  -- The event's own questions: { <question id>: answer }.
  answers jsonb not null default '{}'::jsonb,
  -- [{ type, name, price, quantity }], price in the currency's smallest unit.
  items jsonb not null default '[]'::jsonb,
  quantity integer not null check (quantity > 0),
  amount integer not null check (amount >= 0),
  currency text not null default 'usd',
  refunded_amount integer not null default 0,
  -- A pending order holds its tickets until then.
  expires_at timestamptz,
  paid_at timestamptz,
  checked_in_at timestamptz,
  -- When the confirmation, the reminder and the follow-up went out.
  emailed_at timestamptz,
  reminded_at timestamptz,
  followed_up_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index ticket_orders_entry on public.ticket_orders (entry_id, occurrence, status);
create index ticket_orders_paid on public.ticket_orders (entry_id) where status = 'paid' and (reminded_at is null or followed_up_at is null);
create index ticket_orders_pending on public.ticket_orders (expires_at) where status = 'pending';
create index ticket_orders_provider_ref on public.ticket_orders (provider_ref);
create index ticket_orders_provider_order on public.ticket_orders (provider_order);
create index ticket_orders_provider_payment on public.ticket_orders (provider_payment);

create trigger ticket_orders_touch before update on public.ticket_orders
  for each row execute function public.touch_updated_at();

alter table public.ticket_orders enable row level security;
create policy "ticket orders editor read" on public.ticket_orders for select to authenticated using ((select public.is_editor()));
create policy "ticket orders editor update" on public.ticket_orders for update to authenticated
  using ((select public.is_editor())) with check ((select public.is_editor()));
revoke all on public.ticket_orders from anon;
revoke insert, delete on public.ticket_orders from authenticated;

-- Tickets taken per type for an event (and date): paid orders and pending ones still holding theirs.
create or replace function public.ticket_sold(p_entry bigint, p_occurrence text default '')
returns table (type text, quantity bigint)
language sql
stable
security definer
set search_path = ''
as $$
  select i->>'type', sum((i->>'quantity')::int)::bigint
  from public.ticket_orders o, jsonb_array_elements(o.items) i
  where o.entry_id = p_entry and o.occurrence = coalesce(p_occurrence, '')
    and (o.status = 'paid' or (o.status = 'pending' and o.expires_at > now()))
  group by 1;
$$;

-- One order as its buyer sees it, by its token.
create or replace function public.ticket_order_status(p_token text)
returns table (code text, status text, name text, email text, items jsonb, quantity integer, amount integer, currency text, entry_id bigint, occurrence text, event_title text, paid_at timestamptz)
language sql
stable
security definer
set search_path = ''
as $$
  select code, status, name, email, items, quantity, amount, currency, entry_id, occurrence, event_title, paid_at
  from public.ticket_orders where token = p_token and length(p_token) >= 24;
$$;

-- A new order, if its tickets are still there. One order at a time per event and date (an advisory
-- lock), so two buyers can't both take the last ticket. p_limits: { total: n | null, types: { <type>: n | null } }.
create or replace function public.ticket_order_create(p_order jsonb, p_limits jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_entry bigint := (p_order->>'entry_id')::bigint;
  v_occurrence text := coalesce(p_order->>'occurrence', '');
  v_taken jsonb;
  v_all bigint;
  v_want bigint;
  v_item jsonb;
  v_limit bigint;
  v_id bigint;
begin
  perform pg_advisory_xact_lock(hashtextextended('tickets:' || v_entry || ':' || v_occurrence, 0));
  select coalesce(jsonb_object_agg(s.type, s.quantity), '{}'::jsonb), coalesce(sum(s.quantity), 0)
    into v_taken, v_all from public.ticket_sold(v_entry, v_occurrence) s;
  select coalesce(sum((i->>'quantity')::int), 0) into v_want from jsonb_array_elements(p_order->'items') i;
  for v_item in select * from jsonb_array_elements(p_order->'items') loop
    v_limit := nullif(p_limits->'types'->>(v_item->>'type'), '')::bigint;
    if v_limit is not null and coalesce((v_taken->>(v_item->>'type'))::bigint, 0) + (v_item->>'quantity')::int > v_limit then
      return jsonb_build_object('ok', false, 'type', v_item->>'type', 'left', greatest(v_limit - coalesce((v_taken->>(v_item->>'type'))::bigint, 0), 0));
    end if;
  end loop;
  v_limit := nullif(p_limits->>'total', '')::bigint;
  if v_limit is not null and v_all + v_want > v_limit then
    return jsonb_build_object('ok', false, 'left', greatest(v_limit - v_all, 0));
  end if;
  insert into public.ticket_orders (token, code, entry_id, occurrence, event_title, status, provider, name, email, phone, address, answers, items, quantity, amount, currency, expires_at, paid_at)
  values (
    p_order->>'token', p_order->>'code', v_entry, v_occurrence, coalesce(p_order->>'event_title', ''),
    p_order->>'status', p_order->>'provider', p_order->>'name', p_order->>'email', coalesce(p_order->>'phone', ''),
    nullif(p_order->'address', 'null'::jsonb), coalesce(p_order->'answers', '{}'::jsonb), p_order->'items',
    v_want, (p_order->>'amount')::int, coalesce(p_order->>'currency', 'usd'),
    nullif(p_order->>'expires_at', '')::timestamptz, nullif(p_order->>'paid_at', '')::timestamptz
  )
  returning id into v_id;
  return jsonb_build_object('ok', true, 'id', v_id);
end;
$$;

revoke execute on function public.ticket_order_create(jsonb, jsonb) from public, anon, authenticated;
grant execute on function public.ticket_order_create(jsonb, jsonb) to service_role;
grant execute on function public.ticket_sold(bigint, text) to anon, authenticated, service_role;
grant execute on function public.ticket_order_status(text) to anon, authenticated, service_role;

-- The waitlist for a sold-out event (and date): people told, in order, when tickets free up.
create table public.ticket_waitlist (
  id bigint generated by default as identity primary key,
  entry_id bigint references public.entries (id) on delete cascade,
  occurrence text not null default '',
  name text not null,
  email text not null,
  phone text not null default '',
  quantity integer not null default 1 check (quantity > 0),
  -- waiting; notified (told tickets are available); bought (an order came from the same email); removed.
  status text not null default 'waiting' check (status in ('waiting', 'notified', 'bought', 'removed')),
  notified_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (entry_id, occurrence, email)
);

create index ticket_waitlist_entry on public.ticket_waitlist (entry_id, occurrence, status, id);

create trigger ticket_waitlist_touch before update on public.ticket_waitlist
  for each row execute function public.touch_updated_at();

alter table public.ticket_waitlist enable row level security;
create policy "ticket waitlist editor read" on public.ticket_waitlist for select to authenticated using ((select public.is_editor()));
create policy "ticket waitlist editor update" on public.ticket_waitlist for update to authenticated
  using ((select public.is_editor())) with check ((select public.is_editor()));
revoke all on public.ticket_waitlist from anon;
revoke insert, delete on public.ticket_waitlist from authenticated;
